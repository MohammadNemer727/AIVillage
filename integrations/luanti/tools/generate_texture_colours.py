#!/usr/bin/env python3
"""Average colour and coverage of every texture the founder's eyes may meet.

The founder's eye rays report a colour for whatever block they hit. Blocks from an installed game
(such as Minetest Game) are not in the mod's palette, so this script averages each texture file's
opaque pixels and records how much of the texture is opaque. Lua composites a block's texture
string from these at runtime (base, then overlays by coverage).

Usage: generate_texture_colours.py [--check] GAME_DIR...
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1] / "games/ai_village/mods/ai_bridge"
OUTPUT = ROOT / "texture_colours_generated.lua"


def average(path: Path) -> tuple[int, int, int, int] | None:
    try:
        image = Image.open(path).convert("RGBA")
    except OSError:
        return None
    pixels = [pixel for pixel in image.get_flattened_data() if pixel[3] >= 128]
    total = image.width * image.height
    if not pixels or total == 0:
        return None
    count = len(pixels)
    red = sum(pixel[0] for pixel in pixels) // count
    green = sum(pixel[1] for pixel in pixels) // count
    blue = sum(pixel[2] for pixel in pixels) // count
    coverage = count * 255 // total
    return red, green, blue, coverage


def generated(game_dirs: list[Path]) -> str:
    colours: dict[str, tuple[int, int, int, int]] = {}
    for game_dir in game_dirs:
        for path in sorted(game_dir.rglob("*.png")):
            if path.name not in colours and (summary := average(path)):
                colours[path.name] = summary
    lines = [
        "-- Generated by ../../../../tools/generate_texture_colours.py; do not edit.",
        "-- texture file = {red, green, blue, coverage of opaque pixels out of 255}",
        "return {",
    ]
    lines += [f'  ["{name}"] = {{{r}, {g}, {b}, {c}}},' for name, (r, g, b, c) in sorted(colours.items())]
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    args = sys.argv[1:]
    check = "--check" in args
    game_dirs = [Path(arg) for arg in args if arg != "--check"]
    if not game_dirs:
        print(__doc__, file=sys.stderr)
        return 2
    expected = generated(game_dirs)
    if check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            print("texture_colours_generated.lua is stale; regenerate it", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(expected)
    print(f"wrote {OUTPUT} with {expected.count(chr(10)) - 4} textures")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
